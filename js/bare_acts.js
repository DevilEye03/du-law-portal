/**
 * Find a specific section by Act ID/Code and section number
 */
window.BARE_ACTS_DB.findSection = function(actIdOrCode, sec) {
  if (!sec) return null;
  const cleanSec = String(sec).trim().toLowerCase();
  const cleanAct = actIdOrCode ? String(actIdOrCode).trim().toLowerCase() : '';
  
  return this.sections.find(s => {
    const actMatch = !cleanAct || 
      s.actId.toLowerCase() === cleanAct || 
      s.act.toLowerCase().includes(cleanAct) || 
      (s.keywords && s.keywords.some(k => k.toLowerCase() === cleanAct));
    const secMatch = s.sec.toLowerCase() === cleanSec || 
      s.sec.toLowerCase().replace(/[^a-z0-9]/g, '') === cleanSec.replace(/[^a-z0-9]/g, '') ||
      s.id.toLowerCase().endsWith(cleanSec);
    return actMatch && secMatch;
  });
};

/**
 * Get all sections belonging to a specific Act ID
 */
window.BARE_ACTS_DB.getByAct = function(actId) {
  if (!actId || actId === 'all') return this.sections;
  const cleanAct = actId.toLowerCase();
  return this.sections.filter(s => s.actId.toLowerCase() === cleanAct);
};

/**
 * Search statutory database across Section numbers, Titles, Verbatim text,
 * Ingredients, Explanations, Cases, and Keywords
 */
window.BARE_ACTS_DB.search = function(query, filterActId) {
  if (!query && (!filterActId || filterActId === 'all')) return this.sections;
  const q = (query || '').toLowerCase().trim();
  const act = filterActId && filterActId !== 'all' ? filterActId.toLowerCase() : null;

  return this.sections.filter(s => {
    if (act && s.actId.toLowerCase() !== act) return false;
    if (!q) return true;
    
    // Check section number
    if (s.sec && s.sec.toLowerCase().includes(q)) return true;
    // Check title
    if (s.title && s.title.toLowerCase().includes(q)) return true;
    // Check unit / badge
    if (s.unit && s.unit.toLowerCase().includes(q)) return true;
    if (s.badge && s.badge.toLowerCase().includes(q)) return true;
    // Check verbatim text
    if (s.text && s.text.toLowerCase().includes(q)) return true;
    // Check plain English explanation
    if (s.explanation && s.explanation.toLowerCase().includes(q)) return true;
    // Check ingredients
    if (s.ingredients && s.ingredients.some(ing => ing.toLowerCase().includes(q))) return true;
    // Check cases
    if (s.cases && s.cases.some(c => c.toLowerCase().includes(q))) return true;
    // Check exam tips
    if (s.examTips && s.examTips.toLowerCase().includes(q)) return true;
    // Check legacy analysis
    if (s.analysis && s.analysis.toLowerCase().includes(q)) return true;
    // Check keywords
    if (s.keywords && s.keywords.some(k => k.toLowerCase().includes(q))) return true;
    
    return false;
  });
};
